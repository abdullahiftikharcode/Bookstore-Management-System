class Author:
    def __init__(self,name,gender,email,genre,phonenumber,adresss):
       self.m_name=name
       self.m_gender=gender
       self.m_email=email
       self.m_genre=genre
       self.m_phonenumber=phonenumber
       self.m_address=adresss
    def get_name(self):
        return self.m_name

    def get_gender(self):
        return self.m_gender

    def get_email(self):
        return self.m_email

    def get_genre(self):
        return self.m_genre

    def get_phonenumber(self):
        return self.m_phonenumber
    def get_address(self):
        return self.m_address
    def set_name(self, name):
        self.m_name = name

    def set_gender(self, gender):
        self.m_gender = gender

    def set_email(self, email):
        self.m_email = email

    def set_genre(self, genre):
        self.m_genre = genre

    def set_phonenumber(self, phonenumber):
        self.m_phonenumber = phonenumber

    def set_address(self, address):
        self.m_address = address
       
    
        
    
    




